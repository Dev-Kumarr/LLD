package Model;

public class BallingScoreCard {
    int wicketsTaken;
    int runsGiven;
    int ballsDelivered;
    int economy;
    int noBalls;
    int wideBalls;

    public int getWicketsTaken() {
        return wicketsTaken;
    }

    public void setWicketsTaken(int wicketsTaken) {
        this.wicketsTaken = wicketsTaken;
    }

    public int getRunsGiven() {
        return runsGiven;
    }

    public void setRunsGiven(int runsGiven) {
        this.runsGiven = runsGiven;
    }

    public int getBallsDelivered() {
        return ballsDelivered;
    }

    public void setBallsDelivered(int ballsDelivered) {
        this.ballsDelivered = ballsDelivered;
    }

    public int getEconomy() {
        return economy;
    }

    public void setEconomy(int economy) {
        this.economy = economy;
    }

    public int getNoBalls() {
        return noBalls;
    }

    public void setNoBalls(int noBalls) {
        this.noBalls = noBalls;
    }

    public int getWideBalls() {
        return wideBalls;
    }

    public void setWideBalls(int wideBalls) {
        this.wideBalls = wideBalls;
    }
}